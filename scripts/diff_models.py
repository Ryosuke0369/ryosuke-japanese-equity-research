"""diff_models.py - compare two DCF workbooks cell-for-cell on the numbers that matter.

Why: "the regenerated model validates" is not the same claim as "the regenerated
model produces the same numbers". A regression test for a template change has to
compare VALUES against the reference workbook, which is what this does.

    python scripts/diff_models.py REFERENCE.xlsx CANDIDATE.xlsx
    python scripts/diff_models.py REF.xlsx CAND.xlsx --tolerance 0.005 --all-sheets

Both files must be recalculated (scripts/recalc_excel_com.py) — the comparison
reads Excel's cached values, so an un-recalced workbook compares as all-empty.

By default it walks a fixed list of decision-relevant cells (WACC, the two DCF
legs, the Target, the reverse-DCF answer, the comps statistics). --all-sheets
additionally diffs every populated cell of every shared sheet, which is how you
find the changes you did not think to look for.

Exit code 1 if any compared cell differs by more than the tolerance.
"""
